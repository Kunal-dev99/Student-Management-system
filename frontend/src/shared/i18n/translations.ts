// Merge each language's nav labels + common phrases + extended UI + DB enum values.
// DB_ENUMS keys are the raw DB values ("in_person"); we ALSO add the humanised space
// variant ("in person") to the same translation so both forms match.
for (const code of Object.keys(TRANSLATIONS) as LanguageCode[]) {
  Object.assign(TRANSLATIONS[code], COMMON[code])
  Object.assign(TRANSLATIONS[code], EXTENDED[code])
  const enums = DB_ENUMS[code] ?? {}
  for (const [key, value] of Object.entries(enums)) {
    TRANSLATIONS[code][key] = value
    if (key.includes('_')) {
      // "in_person" also displayed as "in person" throughout the UI — same translation.
      TRANSLATIONS[code][key.replace(/_/g, ' ')] = value
    }
  }
}

export function translate(lang: LanguageCode, key: string): string {
  return TRANSLATIONS[lang]?.[key] ?? TRANSLATIONS.en[key] ?? key
}

/**
 * Runtime DOM translator — walks every text node in `root`, and if its trimmed content
 * exactly matches a dictionary entry, swaps in the localised string. This lets ~200
 * common phrases translate across the whole app without wrapping every render with `t()`.
 *
 * Skipped:
 *  - Text inside <script>, <style>, <textarea>, <input>, <code>, <pre>
 *  - Any subtree marked `data-i18n-skip` (used to keep Settings screens English)
 *  - Nodes whose text doesn't have a dictionary hit — they stay untouched, so dynamic
 *    values like student names, numbers, dates never get mangled.
 *
 * Original English is preserved via `data-i18n-original` so a subsequent language change
 * (or reverting to English) restores the source text instead of translating a translation.
 */
const SKIP_TAGS = new Set(['SCRIPT', 'STYLE', 'TEXTAREA', 'INPUT', 'CODE', 'PRE', 'NOSCRIPT'])

// Original English source per text NODE (not per parent — a parent can have multiple
// text children, and caching on the parent caused sibling text nodes to overwrite each
// other, producing duplicated words like "Score Score"). A WeakMap keeps the cache
// alive only as long as the node is in the DOM.
const ORIGINAL_CACHE: WeakMap<Text, string> = new WeakMap()

// Reverse index — every known translation → its English source. Used to detect
// text nodes we've already translated (in case a browser extension re-renders text
// or React swaps children between updates). Built lazily.
let REVERSE_INDEX: Map<string, string> | null = null
function reverseIndex(): Map<string, string> {
  if (REVERSE_INDEX) return REVERSE_INDEX
  const m = new Map<string, string>()
  for (const code of Object.keys(TRANSLATIONS) as LanguageCode[]) {
    for (const [en, translated] of Object.entries(TRANSLATIONS[code])) {
      if (translated !== en) m.set(translated, en)
    }
  }
  REVERSE_INDEX = m
  return m
}

export function translateSubtree(root: Node, lang: LanguageCode) {
  const dict = TRANSLATIONS[lang] ?? TRANSLATIONS.en
  const rev = reverseIndex()
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode: (node) => {
      const parent = node.parentElement
      if (!parent) return NodeFilter.FILTER_REJECT
      if (SKIP_TAGS.has(parent.tagName)) return NodeFilter.FILTER_REJECT
      if (parent.closest('[data-i18n-skip="true"]')) return NodeFilter.FILTER_REJECT
      const text = node.nodeValue?.trim()
      if (!text) return NodeFilter.FILTER_REJECT
      return NodeFilter.FILTER_ACCEPT
    },
  })
  const nodes: Text[] = []
  let n: Node | null
  while ((n = walker.nextNode())) nodes.push(n as Text)
  for (const node of nodes) {
    // Resolve the original English source for this specific node.
    let original = ORIGINAL_CACHE.get(node)
    if (original == null) {
      const current = node.nodeValue ?? ''
      const trimmedCurrent = current.trim()
      // If the current text is already a known translation of something, back-solve
      // to the English source so subsequent language switches work correctly.
      original = rev.get(trimmedCurrent)
        ? current.replace(trimmedCurrent, rev.get(trimmedCurrent)!)
        : current
      ORIGINAL_CACHE.set(node, original)
    }
    const trimmed = original.trim()
    const hit = dict[trimmed]
    const nextValue = hit ? original.replace(trimmed, hit) : original
    // Only assign if the value would actually change — avoids waking the
    // MutationObserver unnecessarily.
    if (node.nodeValue !== nextValue) node.nodeValue = nextValue
  }
}
